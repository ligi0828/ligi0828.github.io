/* ============================================================
   i18n engine
   ============================================================ */

const I18n = {
  current: "zh",

  detect() {
    const saved = localStorage.getItem("lang");
    if (saved && I18N[saved]) return saved;
    const nav = (navigator.language || "zh").slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : "zh";
  },

  set(lang) {
    if (!I18N[lang]) lang = "zh";
    this.current = lang;
    localStorage.setItem("lang", lang);
    document.documentElement.lang = lang;
    const sel = document.getElementById("langSelect");
    if (sel) sel.value = lang;
    this.apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  },

  t(key, vars) {
    let str = (I18N[this.current] && I18N[this.current][key]) || I18N.zh[key] || key;
    if (vars) {
      for (const k in vars) {
        str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      }
    }
    return str;
  },

  apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = this.t(el.dataset.i18nPh);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", this.t(el.dataset.i18nTitle));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.dataset.i18nAria));
    });
    const title = document.querySelector("title");
    if (title && title.dataset.i18n) title.textContent = this.t(title.dataset.i18n);
  }
};
